SELECT 'CLEAN', COUNT(*) FROM FACT_SALES;
GO

-- =============================================
-- 6. DATA QUALITY CHECK
-- =============================================

-- NULOS
SELECT 
    COUNT(*) AS TOTAL_ROWS,
    SUM(CASE WHEN TOTAL_VALUE_SALES IS NULL THEN 1 ELSE 0 END) AS NULL_VALUES
FROM FACT_SALES;
GO

-- MATCH DE JOIN
SELECT 
    COUNT(*) AS MATCHED_ROWS
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON REPLACE(f.ITEM_CODE,'"','') = REPLACE(p.ITEM,'"','');
GO

-- NO MATCH
SELECT COUNT(*) AS UNMATCHED_ROWS
FROM FACT_SALES f
LEFT JOIN DIM_PRODUCT p
    ON REPLACE(f.ITEM_CODE,'"','') = REPLACE(p.ITEM,'"','')
WHERE p.ITEM IS NULL;
GO

-- =============================================
-- 7. ANALYTICS
-- =============================================

-- VENTAS POR REGIÓN
SELECT 
    REGION,
    SUM(TOTAL_VALUE_SALES) AS TOTAL_SALES
FROM FACT_SALES
GROUP BY REGION
ORDER BY TOTAL_SALES DESC;
GO

-- TOP PRODUCTOS
SELECT TOP 5
    ITEM_CODE,
    SUM(TOTAL_VALUE_SALES) AS TOTAL_SALES
FROM FACT_SALES
GROUP BY ITEM_CODE
ORDER BY TOTAL_SALES DESC;
GO

-- VENTAS POR CATEGORÍA
SELECT 
    c.CATEGORY AS CATEGORY_NAME,
    SUM(f.TOTAL_VALUE_SALES) AS TOTAL_SALES
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON REPLACE(f.ITEM_CODE,'"','') = REPLACE(p.ITEM,'"','')
JOIN DIM_CATEGORY c
    ON p.CATEGORY = c.ID_CATEGORY
GROUP BY c.CATEGORY
ORDER BY TOTAL_SALES DESC;
GO

-- =============================================
-- 8. ANÁLISIS TEMPORAL
-- =============================================

SELECT 
    WEEK,
    SUM(TOTAL_VALUE_SALES) AS TOTAL_SALES
FROM FACT_SALES
GROUP BY WEEK
