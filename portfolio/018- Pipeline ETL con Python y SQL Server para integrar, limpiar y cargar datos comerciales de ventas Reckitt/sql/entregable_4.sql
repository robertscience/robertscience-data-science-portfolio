GO

SELECT TOP 1
    WEEK,
    SUM(TOTAL_VALUE_SALES) AS TOTAL_SALES
FROM FACT_SALES
GROUP BY WEEK
ORDER BY TOTAL_SALES DESC;
GO

-- =============================================
-- 9. KPI
-- =============================================

-- PRECIO PROMEDIO
SELECT 
    SUM(TOTAL_VALUE_SALES) / NULLIF(SUM(TOTAL_UNIT_SALES),0) AS AVG_PRICE
FROM FACT_SALES;
GO

-- PRECIO POR PRODUCTO
SELECT TOP 10
    ITEM_CODE,
    SUM(TOTAL_VALUE_SALES) / NULLIF(SUM(TOTAL_UNIT_SALES),0) AS PRICE_PER_UNIT
FROM FACT_SALES
GROUP BY ITEM_CODE
ORDER BY PRICE_PER_UNIT DESC;
GO

-- =============================================
-- 10. VISTA ANALÍTICA
-- =============================================

CREATE OR ALTER VIEW VW_SALES_ANALYSIS AS
SELECT 
    f.WEEK,
    f.REGION,
    p.BRAND,
    c.CATEGORY,
    f.TOTAL_VALUE_SALES,
    f.TOTAL_UNIT_SALES
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON REPLACE(f.ITEM_CODE,'"','') = REPLACE(p.ITEM,'"','')
JOIN DIM_CATEGORY c
    ON p.CATEGORY = c.ID_CATEGORY;
GO

-- USO DE LA VISTA
SELECT 
    CATEGORY,
    SUM(TOTAL_VALUE_SALES) AS TOTAL_SALES
FROM VW_SALES_ANALYSIS
GROUP BY CATEGORY
ORDER BY TOTAL_SALES DESC;
GO

-- =============================================
-- SALES BY CATEGORY NAME
-- =============================================

SELECT 
    c.CATEGORY AS CATEGORY_NAME,
    SUM(f.TOTAL_VALUE_SALES) AS TOTAL_SALES
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON f.ITEM_CODE = REPLACE(p.ITEM,'"','')
JOIN DIM_CATEGORY c
    ON p.CATEGORY = c.ID_CATEGORY
GROUP BY c.CATEGORY
ORDER BY TOTAL_SALES DESC;
GO

CREATE INDEX IDX_FACT_ITEM ON FACT_SALES(ITEM_CODE);
CREATE INDEX IDX_FACT_REGION ON FACT_SALES(REGION);
CREATE INDEX IDX_PRODUCT_ITEM ON DIM_PRODUCT(ITEM);
GO

-- =============================================
-- 11. BUSINESS INSIGHT
-- =============================================

SELECT 
    c.CATEGORY AS CATEGORY_NAME,
    f.REGION,
    SUM(f.TOTAL_VALUE_SALES) AS SALES,
    SUM(f.TOTAL_UNIT_SALES) AS UNITS,
    SUM(f.TOTAL_VALUE_SALES) / NULLIF(SUM(f.TOTAL_UNIT_SALES),0) AS PRICE
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON f.ITEM_CODE = REPLACE(p.ITEM,'"','')
JOIN DIM_CATEGORY c
    ON p.CATEGORY = c.ID_CATEGORY
GROUP BY c.CATEGORY, f.REGION
ORDER BY SALES DESC;
GO