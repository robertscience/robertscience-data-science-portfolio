-- =============================================
-- 4. CLEAN LAYER
-- =============================================

DROP TABLE IF EXISTS FACT_SALES;
GO

SELECT
    LTRIM(RTRIM(WEEK)) AS WEEK,

    REPLACE(REPLACE(LTRIM(RTRIM(ITEM_CODE)),'"',''),' ','') AS ITEM_CODE,

    TRY_CONVERT(FLOAT, REPLACE(REPLACE(TOTAL_UNIT_SALES,'"',''),',','')) AS TOTAL_UNIT_SALES,
    TRY_CONVERT(FLOAT, REPLACE(REPLACE(TOTAL_VALUE_SALES,'"',''),',','')) AS TOTAL_VALUE_SALES,
    TRY_CONVERT(FLOAT, REPLACE(REPLACE(TOTAL_UNIT_AVG_WEEKLY_SALES,'"',''),',','')) AS AVG_WEEKLY_SALES,

    LTRIM(RTRIM(REGION)) AS REGION
INTO FACT_SALES
FROM FACT_SALES_RAW;
GO

PRINT 'CLEAN FACT CREATED';
GO

-- =============================================
-- 5. VALIDACIÓN
